#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..', 'client', 'src')
const OUT = path.resolve(__dirname, '..', 'docs', 'visual-spec.md')

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(p, out)
    else if (/\.(tsx|ts|css|html)$/.test(entry.name)) out.push(p)
  }
  return out
}

function extractFromFile(filePath, src) {
  const classNames = []
  const inlineStyles = []
  const cssClasses = []
  const cssRules = []

  if (filePath.endsWith('.css')) {
    const ruleRe = /([^{}\n][^{}]*)\{([^}]*)\}/g
    let m
    while ((m = ruleRe.exec(src))) {
      const selector = m[1].trim().replace(/\s+/g, ' ')
      const body = m[2].trim().replace(/\s+/g, ' ')
      if (selector && body) cssRules.push({ selector, body })
      const classMatches = selector.match(/\.[A-Za-z_][\w-]*/g)
      if (classMatches) classMatches.forEach((c) => cssClasses.push(c))
    }
    return { classNames, inlineStyles, cssClasses: [...new Set(cssClasses)], cssRules }
  }

  // className="..." (double quote)
  const dq = /className="([^"]+)"/g
  let m
  while ((m = dq.exec(src))) classNames.push({ kind: 'static', value: m[1].trim() })

  // className='...' (single quote)
  const sq = /className='([^']+)'/g
  while ((m = sq.exec(src))) classNames.push({ kind: 'static', value: m[1].trim() })

  // className={`...`} -- template literal (may contain ${...} expressions)
  const tl = /className=\{`([\s\S]*?)`\}/g
  while ((m = tl.exec(src))) classNames.push({ kind: 'template', value: m[1].replace(/\s+/g, ' ').trim() })

  // className={...} -- generic JS expression (capture for visibility)
  const exprRe = /className=\{(?!\s*`)([^{}]*(?:\{[^}]*\}[^{}]*)*)\}/g
  while ((m = exprRe.exec(src))) {
    const v = m[1].replace(/\s+/g, ' ').trim()
    if (v && !v.startsWith('`')) classNames.push({ kind: 'expr', value: v })
  }

  // inline style={{...}} blocks
  const styleRe = /style=\{\{([\s\S]*?)\}\}/g
  while ((m = styleRe.exec(src))) inlineStyles.push(m[1].replace(/\s+/g, ' ').trim())

  return { classNames, inlineStyles, cssClasses, cssRules }
}

const files = walk(ROOT).filter((f) => !f.endsWith('.d.ts'))
files.sort()

const lines = []
lines.push('# Visual Spec — Rental City Frontend')
lines.push('')
lines.push(`Auto-generated by \`scripts/extract-visual-spec.mjs\` from \`client/src/\`. ${files.length} files scanned.`)
lines.push('')
lines.push('For each file, three sections:')
lines.push('- **className (static)** — string literals: `className="..."`')
lines.push('- **className (template)** — backtick literals: `` className={`...`} `` (with `${expr}` interpolations preserved as text)')
lines.push('- **className (expr)** — JS expressions: `className={cond ? a : b}` (raw expression captured)')
lines.push('- **inline styles** — `style={{...}}` blocks')
lines.push('')
lines.push('---')
lines.push('')

const summaryStats = []

for (const file of files) {
  const rel = path.relative(path.resolve(__dirname, '..'), file)
  const src = fs.readFileSync(file, 'utf8')
  const { classNames, inlineStyles, cssClasses, cssRules } = extractFromFile(file, src)
  const isCss = file.endsWith('.css')
  const hasContent = classNames.length || inlineStyles.length || cssRules.length
  if (!hasContent) {
    summaryStats.push({ file: rel, classes: 0, styles: 0, cssRules: 0 })
    continue
  }

  lines.push(`## \`${rel}\``)
  lines.push('')

  if (isCss && cssRules.length) {
    lines.push(`**CSS rules (${cssRules.length}):**`)
    lines.push('')
    lines.push('```css')
    for (const r of cssRules) lines.push(`${r.selector} { ${r.body} }`)
    lines.push('```')
    lines.push('')
  }

  const staticCns = classNames.filter((c) => c.kind === 'static')
  const tmplCns = classNames.filter((c) => c.kind === 'template')
  const exprCns = classNames.filter((c) => c.kind === 'expr')

  if (staticCns.length) {
    lines.push(`**className — static (${staticCns.length}):**`)
    lines.push('')
    lines.push('```')
    staticCns.forEach((c, i) => lines.push(`${String(i + 1).padStart(3, ' ')}. ${c.value}`))
    lines.push('```')
    lines.push('')
  }

  if (tmplCns.length) {
    lines.push(`**className — template literal (${tmplCns.length}):**`)
    lines.push('')
    lines.push('```')
    tmplCns.forEach((c, i) => lines.push(`${String(i + 1).padStart(3, ' ')}. \`${c.value}\``))
    lines.push('```')
    lines.push('')
  }

  if (exprCns.length) {
    lines.push(`**className — JS expression (${exprCns.length}):**`)
    lines.push('')
    lines.push('```')
    exprCns.forEach((c, i) => lines.push(`${String(i + 1).padStart(3, ' ')}. {${c.value}}`))
    lines.push('```')
    lines.push('')
  }

  if (inlineStyles.length) {
    lines.push(`**inline styles (${inlineStyles.length}):**`)
    lines.push('')
    lines.push('```js')
    inlineStyles.forEach((s, i) => lines.push(`${String(i + 1).padStart(3, ' ')}. {{ ${s} }}`))
    lines.push('```')
    lines.push('')
  }

  lines.push('---')
  lines.push('')

  summaryStats.push({
    file: rel,
    classes: classNames.length,
    styles: inlineStyles.length,
    cssRules: cssRules.length,
  })
}

// Append global utility-class frequency table
const allUtils = new Map()
for (const file of files) {
  const src = fs.readFileSync(file, 'utf8')
  const re = /className=(?:"([^"]+)"|'([^']+)'|\{`([^`]+)`\})/g
  let m
  while ((m = re.exec(src))) {
    const v = m[1] || m[2] || m[3] || ''
    v.split(/\s+/).filter(Boolean).forEach((cls) => {
      if (cls.startsWith('${') || cls.endsWith('}')) return
      allUtils.set(cls, (allUtils.get(cls) || 0) + 1)
    })
  }
}

const sorted = [...allUtils.entries()].sort((a, b) => b[1] - a[1])
lines.push('')
lines.push('# Appendix A — Global Tailwind Utility Frequency')
lines.push('')
lines.push(`${sorted.length} unique utility tokens across all files. Top 200 by frequency:`)
lines.push('')
lines.push('| Utility | Count |')
lines.push('|---|---|')
for (const [k, v] of sorted.slice(0, 200)) lines.push(`| \`${k}\` | ${v} |`)
lines.push('')
lines.push('<details><summary>Full list (all unique utilities)</summary>')
lines.push('')
lines.push('```')
for (const [k, v] of sorted) lines.push(`${String(v).padStart(4, ' ')}  ${k}`)
lines.push('```')
lines.push('')
lines.push('</details>')
lines.push('')

lines.push('# Appendix B — Per-file size summary')
lines.push('')
lines.push('| File | className count | inline style count | CSS rule count |')
lines.push('|---|---:|---:|---:|')
for (const s of summaryStats) lines.push(`| \`${s.file}\` | ${s.classes} | ${s.styles} | ${s.cssRules} |`)
lines.push('')

fs.mkdirSync(path.dirname(OUT), { recursive: true })
fs.writeFileSync(OUT, lines.join('\n'))

const stat = fs.statSync(OUT)
console.log(`Wrote ${OUT}`)
console.log(`  size: ${(stat.size / 1024).toFixed(1)} KB`)
console.log(`  lines: ${lines.length}`)
console.log(`  unique utilities: ${sorted.length}`)
console.log(`  files with visual content: ${summaryStats.filter((s) => s.classes || s.styles || s.cssRules).length}/${summaryStats.length}`)
